import logging
from datetime import datetime, timezone

from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.auth.api_key import validate_api_key
from app.database import get_session
from app.models.pattern import Pattern
from app.schemas.auto_review import AutoReviewRequest, AutoReviewResponse
from app.services.anthropic_service import generate_fixes, plan_review
from app.services.github_service import (
    create_branch,
    create_or_update_file,
    create_pull_request,
    get_branch_sha,
    parse_diff_files,
    post_review,
)

logger = logging.getLogger(__name__)
router = APIRouter(tags=["auto-review"])

REPORT_FILE = "review-report.md"


def _build_report(plan, repository: str, pr_number: int, pr_url: str | None = None) -> str:
    """Build a markdown report from the review plan."""
    severity_order = {"critical": 0, "warning": 1, "suggestion": 2}
    sorted_issues = sorted(plan.issues, key=lambda i: severity_order.get(i.severity, 99))

    lines = [
        f"# ResolveAI Review Report",
        f"",
        f"**Repository:** {repository}",
        f"**PR:** #{pr_number}",
        f"**Date:** {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}",
        f"",
        f"## Summary",
        f"",
        f"{plan.summary}",
        f"",
        f"## Findings ({len(plan.issues)} total)",
        f"",
    ]

    criticals = [i for i in sorted_issues if i.severity == "critical"]
    warnings = [i for i in sorted_issues if i.severity == "warning"]
    suggestions = [i for i in sorted_issues if i.severity == "suggestion"]

    lines.append(f"- 🔴 Critical: {len(criticals)}")
    lines.append(f"- 🟡 Warning: {len(warnings)}")
    lines.append(f"- 💡 Suggestion: {len(suggestions)}")
    lines.append(f"")

    if sorted_issues:
        lines.append("## Detailed Issues")
        lines.append("")

        for idx, issue in enumerate(sorted_issues, 1):
            severity_badge = {
                "critical": "🔴 **Critical**",
                "warning": "🟡 **Warning**",
                "suggestion": "💡 **Suggestion**",
            }.get(issue.severity, issue.severity)

            lines.append(f"### {idx}. {severity_badge}")
            lines.append(f"")
            if issue.file:
                lines.append(f"**File:** `{issue.file}` (lines {issue.line_start}-{issue.line_end})")
                lines.append(f"")
            lines.append(f"**Description:** {issue.description}")
            lines.append(f"")
            if issue.suggestion:
                lines.append(f"**Suggested fix:**")
                lines.append(f"```")
                lines.append(issue.suggestion)
                lines.append(f"```")
                lines.append(f"")
            if issue.explanation:
                lines.append(f"*{issue.explanation}*")
                lines.append(f"")

    lines.append("---")
    lines.append(f"*Generated by [ResolveAI](https://github.com/resolveAI)*")
    return "\n".join(lines)


@router.post("/auto-review", response_model=AutoReviewResponse)
async def auto_review(
    body: AutoReviewRequest,
    _: str = Depends(validate_api_key),
    db: AsyncSession = Depends(get_session),
):
    """Review code and optionally create a PR with an inline review + markdown report."""

    # Load patterns
    result = await db.execute(
        select(Pattern).where(
            Pattern.repository == body.repository, Pattern.name == "default"
        )
    )
    pattern = result.scalar_one_or_none()
    patterns_content = pattern.content if pattern else None

    pr_number = body.pr_number
    pr_url: str | None = None
    pr_created = False
    commit_sha = body.commit_sha

    # Phase 0: create PR if requested and no PR number provided
    if pr_number is None and body.create_pr:
        try:
            # Ensure the head branch exists with the diff content before creating PR
            base_sha = await get_branch_sha(body.repository, body.base_ref, body.github_token)
            await create_branch(body.repository, body.head_ref, base_sha, body.github_token)

            diff_files = parse_diff_files(body.diff_raw)
            for f in diff_files:
                await create_or_update_file(
                    repository=body.repository,
                    file_path=f["path"],
                    content=f["content"],
                    message=f"Add {f['path']}",
                    branch=body.head_ref,
                    github_token=body.github_token,
                )

            # Use the actual commit SHA from the new branch for inline review comments
            commit_sha = await get_branch_sha(body.repository, body.head_ref, body.github_token)

            pr_info = await create_pull_request(
                repository=body.repository,
                title=body.pr_title,
                body=body.pr_body,
                head=body.head_ref,
                base=body.base_ref,
                github_token=body.github_token,
            )
            pr_number = pr_info["number"]
            pr_url = pr_info["html_url"]
            pr_created = True
            logger.info("Created PR #%d: %s", pr_number, pr_url)
        except Exception as exc:
            logger.exception("PR creation failed")
            raise HTTPException(
                status_code=502, detail=f"PR creation failed: {exc}"
            ) from exc
    elif pr_number is None:
        raise HTTPException(
            status_code=400,
            detail="pr_number is required when create_pr is False",
        )

    # Phase 1: planning
    try:
        plan = await plan_review(body.diff_raw, patterns_content)
    except Exception as exc:
        logger.exception("Anthropic planning failed")
        raise HTTPException(status_code=502, detail=f"AI planning failed: {exc}") from exc

    # Phase 2: generate fixes
    try:
        plan = await generate_fixes(plan, body.diff_raw)
    except Exception as exc:
        logger.exception("Anthropic fix generation failed")
        raise HTTPException(status_code=502, detail=f"AI fix generation failed: {exc}") from exc

    # Phase 3: post inline review
    review_id = None
    try:
        review_id = await post_review(
            repository=body.repository,
            pr_number=pr_number,
            commit_sha=commit_sha,
            plan=plan,
            github_token=body.github_token,
            diff_raw=body.diff_raw,
        )
    except Exception as exc:
        logger.exception("GitHub review posting failed")
        raise HTTPException(status_code=502, detail=f"GitHub posting failed: {exc}") from exc

    # Phase 4: create markdown report file in the PR branch
    report_file_path: str | None = None
    if pr_created:
        report_content = _build_report(plan, body.repository, pr_number, pr_url)
        try:
            await create_or_update_file(
                repository=body.repository,
                file_path=REPORT_FILE,
                content=report_content,
                message=f"Add ResolveAI review report for PR #{pr_number}",
                branch=body.head_ref,
                github_token=body.github_token,
            )
            report_file_path = REPORT_FILE
        except Exception as exc:
            logger.warning("Failed to create report file: %s", exc)
            # Non-fatal — review was still posted

    return AutoReviewResponse(
        status="success",
        review_id=review_id,
        pr_number=pr_number,
        pr_url=pr_url,
        comments_count=len(plan.issues),
        summary=plan.summary,
        report_file_path=report_file_path,
    )
